async function ensureProjectTodoIds(projectId: number, todoIds: number[], client?: PoolClient) {
  const normalizedTodoIds = normalizeTodoIds(todoIds)
  if (normalizedTodoIds.length === 0) return []

  const sql = `
    select id
    from todos
    where project_id = $1
      and id = any($2::bigint[])
  `
  const result = client
    ? await client.query<{ id: string }>(sql, [projectId, normalizedTodoIds])
    : await query<{ id: string }>(sql, [projectId, normalizedTodoIds])
  const foundTodoIds = new Set(result.rows.map((row) => Number(row.id)))
  if (foundTodoIds.size !== normalizedTodoIds.length) {
    throw new Error('Some todos were not found in this project')
  }
  return normalizedTodoIds
}

async function replaceOperationTodoLinks(
  client: PoolClient,
  operationId: number,
  authorUserId: number,
  todoIds: number[],
  todoNotes: Record<number, string> = {},
) {
  await client.query(
    `
    delete from project_package_operation_todos
    where project_package_operation_id = $1
    `,
    [operationId],
  )

  for (const todoId of todoIds) {
    const note = String(todoNotes[todoId] ?? '').trim()
    const encryptedNote = note ? encryptText(note) : ''
    await client.query(
      `
      insert into project_package_operation_todos (
        project_package_operation_id,
        todo_id,
        note,
        note_author_user_id
      )
      values ($1, $2, $3, $4)
      on conflict (project_package_operation_id, todo_id) do update
        set note = excluded.note,
            note_author_user_id = case
              when excluded.note <> '' then excluded.note_author_user_id
              else project_package_operation_todos.note_author_user_id
            end
      `,
      [operationId, todoId, encryptedNote, note ? authorUserId : null],
    )
  }
}

async function syncOperationTodoNotes(
  client: PoolClient,
  operationId: number,
  authorUserId: number,
  todoIds: number[],
  todoNotes: Record<number, string> = {},
) {
  const normalizedTodoIds = normalizeTodoIds(todoIds)

  await client.query(
    `
    delete from todo_notes
    where source_operation_id = $1
      and todo_id <> all($2::bigint[])
    `,
    [operationId, normalizedTodoIds.length > 0 ? normalizedTodoIds : [0]],
  )

  for (const todoId of normalizedTodoIds) {
    const note = String(todoNotes[todoId] ?? '').trim()
    if (!note) {
      await client.query(
        `
        delete from todo_notes
        where todo_id = $1
          and source_operation_id = $2
        `,
        [todoId, operationId],
      )
      continue
    }

    await client.query(
      `
      insert into todo_notes (todo_id, author_user_id, content, source_operation_id)
      values ($1, $2, $3, $4)
      on conflict (todo_id, source_operation_id)
        where source_operation_id is not null
      do update
        set content = excluded.content,
            author_user_id = excluded.author_user_id,
            updated_at = now()
      `,
      [todoId, authorUserId, encryptText(note), operationId],
    )
  }
}

async function setTodosDoneState(projectId: number, todoIds: number[], done: boolean) {
  const normalizedTodoIds = await ensureProjectTodoIds(projectId, todoIds)
  if (normalizedTodoIds.length === 0) return

  await query(
    `
    update todos
    set done = $1,
        updated_at = now()
    where project_id = $2
      and id = any($3::bigint[])
    `,
    [done, projectId, normalizedTodoIds],
  )
}

async function listProjectOperationTodoLinks(projectId: number) {
  const result = await query<ProjectOperationTodoLinkRow>(
    `
    select o.id as operation_id,
           t.todo_id
    from project_package_operations o
    join project_package_events e on e.id = o.project_package_event_id
    left join project_package_operation_todos t
      on t.project_package_operation_id = o.id
    where e.project_id = $1
    `,
    [projectId],
  )
  return result.rows
}

function buildProjectCompletionGraph(rows: ProjectOperationTodoLinkRow[]) {
  const operationToTodos = new Map<number, number[]>()
  const todoToOperations = new Map<number, number[]>()

  for (const row of rows) {
    const operationId = Number(row.operation_id)
    if (!operationToTodos.has(operationId)) {
      operationToTodos.set(operationId, [])
    }
    if (!row.todo_id) continue
    const todoId = Number(row.todo_id)
    operationToTodos.set(operationId, [...(operationToTodos.get(operationId) ?? []), todoId])
    todoToOperations.set(todoId, [...(todoToOperations.get(todoId) ?? []), operationId])
  }

  return { operationToTodos, todoToOperations }
}

function collectConnectedProjectCompletionIds(
  graph: ReturnType<typeof buildProjectCompletionGraph>,
  seeds: {
    operationIds?: number[]
    todoIds?: number[]
  },
) {
  const operationIds = new Set(normalizePositiveIds(seeds.operationIds ?? []))
  const todoIds = new Set(normalizePositiveIds(seeds.todoIds ?? []))
  const operationQueue = [...operationIds]
  const todoQueue = [...todoIds]

  while (operationQueue.length > 0 || todoQueue.length > 0) {
    while (operationQueue.length > 0) {
      const operationId = operationQueue.shift()
      if (operationId == null) continue
      for (const todoId of graph.operationToTodos.get(operationId) ?? []) {
        if (todoIds.has(todoId)) continue
        todoIds.add(todoId)
        todoQueue.push(todoId)
      }
    }

    while (todoQueue.length > 0) {
      const todoId = todoQueue.shift()
      if (todoId == null) continue
      for (const operationId of graph.todoToOperations.get(todoId) ?? []) {
        if (operationIds.has(operationId)) continue
        operationIds.add(operationId)
        operationQueue.push(operationId)
      }
    }
  }

  return {
    operationIds: [...operationIds],
    todoIds: [...todoIds],
  }
}

async function setOperationsCompletedState(projectId: number, operationIds: number[], completed: boolean) {
  const normalizedOperationIds = normalizePositiveIds(operationIds)
  if (normalizedOperationIds.length === 0) return

  await query(
    `
    update project_package_operations o
    set completed = $1,
        updated_at = now()
    from project_package_events e
    where o.project_package_event_id = e.id
      and e.project_id = $2
      and o.id = any($3::bigint[])
    `,
    [completed, projectId, normalizedOperationIds],
  )
}

async function touchEventsForOperations(projectId: number, operationIds: number[]) {
  const normalizedOperationIds = normalizePositiveIds(operationIds)
  if (normalizedOperationIds.length === 0) return

  await query(
    `
    update project_package_events e
    set updated_at = now()
    where e.project_id = $1
      and exists (
        select 1
        from project_package_operations o
        where o.project_package_event_id = e.id
          and o.id = any($2::bigint[])
      )
    `,
    [projectId, normalizedOperationIds],
  )
}

export async function syncProjectPackageCompletionState(params: {
  completed: boolean
  operationIds?: number[]
  projectId: number
  todoIds?: number[]
}) {
  const seedOperationIds = normalizePositiveIds(params.operationIds ?? [])
  const seedTodoIds = normalizePositiveIds(params.todoIds ?? [])

  if (seedOperationIds.length === 0 && seedTodoIds.length === 0) {
    return {
      operationIds: [],
      todoIds: [],
    }
  }

  const graph = buildProjectCompletionGraph(await listProjectOperationTodoLinks(params.projectId))
  const connectedIds = collectConnectedProjectCompletionIds(graph, {
    operationIds: seedOperationIds,
    todoIds: seedTodoIds,
  })

  if (connectedIds.operationIds.length > 0) {
    await setOperationsCompletedState(params.projectId, connectedIds.operationIds, params.completed)
  }
  if (connectedIds.todoIds.length > 0) {
    await setTodosDoneState(params.projectId, connectedIds.todoIds, params.completed)
  }
  if (connectedIds.operationIds.length > 0) {
    await touchEventsForOperations(params.projectId, connectedIds.operationIds)
  }

  return connectedIds
}

