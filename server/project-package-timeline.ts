function textValue(value: unknown, fallback = '-') {
  const normalized = String(value ?? '').trim()
  return normalized || fallback
}

function packageDownloadUrlValue(objectKey: string) {
  try {
    return createPackageItemDownloadUrl(objectKey)
  } catch (error) {
    return `临时下载链接生成失败：${String((error as Error).message ?? error)}`
  }
}

function normalizeExportNoteText(value: unknown, fallback = '未填写') {
  const normalized = String(value ?? '').trim()
  if (!normalized) return fallback
  return normalized
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join(' / ')
}

function buildPackageTimelineNodes(group: ProjectPackageGroup) {
  const itemNodes = group.items.map((item) => ({
    type: 'package-operation' as const,
    createdAt: item.createdAt,
    item,
  }))
  const operationNodes = group.operations.map((operation) => ({
    type: operation.kind,
    createdAt: operation.createdAt,
    operation,
  }))
  return [...itemNodes, ...operationNodes].sort((left, right) =>
    left.createdAt.localeCompare(right.createdAt),
  )
}

function buildOperationMarkdown(
  operation: ProjectPackageOperation,
  relatedTodoDetails: OperationRelatedTodoExportDetail[] = [],
  level = '###',
  options: { listStyle?: boolean } = {},
) {
  const createdAt = formatExportDateTime(operation.createdAt)
  const relatedTodoLines = relatedTodoDetails.flatMap((detail, index) => {
    const lines = [
      `- 关联待办：${textValue(detail.title, `#${detail.todoId}`)}`,
      `  - 备注作者：${textValue(detail.noteAuthorName, '未填写')}`,
      `  - 备注内容：${normalizeExportNoteText(detail.note)}`,
    ]
    return index === 0 ? lines : ['', ...lines]
  })
  const relatedTodoBlock = relatedTodoLines.length > 0
    ? ['', '#### 关联待办说明', '', ...relatedTodoLines]
    : []
  if (operation.kind === 'document') {
    return [
      `${level} 文档：${textValue(operation.title, '未命名操作文档')}`,
      '',
      `- 时间：${createdAt}`,
      '',
      textValue(operation.content, '无内容'),
      ...relatedTodoBlock,
    ]
  }

  const eventLabel = textValue(operation.label, '操作事件')
  const operationTitle = textValue(operation.title, '')
  if (options.listStyle) {
    const lines = [`- ${createdAt} · ${eventLabel}`]
    if (operation.content) {
      if (operationTitle && operationTitle !== eventLabel) {
        lines.push('', `  - ${operationTitle}`)
      }
      lines.push('', textValue(operation.content, '无内容'))
    }
    if (relatedTodoLines.length > 0) {
      lines.push('', ...relatedTodoLines)
    }
    return lines
  }

  const detailLevel = `${level}#`
  const lines = [
    `${level} ${createdAt}`,
    '',
    `${detailLevel} ${eventLabel}`,
  ]
  if (operation.content) {
    if (operationTitle && operationTitle !== eventLabel) {
      lines.push('', `${detailLevel}# ${operationTitle}`, '', operation.content)
    } else {
      lines.push('', operation.content)
    }
  }
  lines.push(...relatedTodoBlock)
  return lines
}

function buildPackageTimelineMarkdown(
  group: ProjectPackageGroup,
  relatedTodoDetailsByOperation: Map<number, OperationRelatedTodoExportDetail[]>,
  headingLevel = '##',
) {
  const lines: string[] = []
  const nodes = buildPackageTimelineNodes(group)
  const packageOperations = nodes.filter((node) => node.type !== 'package-operation')
  const packageRecords = nodes.filter((node) => node.type === 'package-operation')

  if (packageRecords.length > 0) {
    const details = packageRecords.map((node) => {
      if (node.type !== 'package-operation') return ''
      const item = node.item
      return [textValue(item.channelLabel), textValue(item.arch), textValue(item.version, '未知版本')]
        .filter(Boolean)
        .join(' · ')
    })
    lines.push(`${headingLevel} ${group.packageName} · ${details.join('；')}`, '')
    lines.push(`${headingLevel}# 临时下载链接`, '')
    packageRecords.forEach((node) => {
      if (node.type !== 'package-operation') return
      const item = node.item
      const label = [
        textValue(item.packageName),
        textValue(item.channelLabel),
        textValue(item.arch),
        textValue(item.version, '未知版本'),
      ].filter(Boolean).join(' · ')
      lines.push(`- ${label}：${packageDownloadUrlValue(item.objectKey)}`)
    })
    lines.push('')
  } else {
    lines.push(`${headingLevel} ${group.packageName}`, '')
  }

  if (packageOperations.length === 0) {
    lines.push('暂无时间线记录。')
    return lines
  }

  packageOperations.forEach((node) => {
    lines.push(
      ...buildOperationMarkdown(
        node.operation,
        relatedTodoDetailsByOperation.get(node.operation.id) ?? [],
        `${headingLevel}#`,
        { listStyle: true },
      ),
      '',
    )
  })

  return lines
}

function countPackageItems(timeline: ProjectPackageTimeline) {
  return timeline.events.reduce(
    (total, event) =>
      total + event.groups.reduce((eventTotal, group) => eventTotal + group.items.length, 0),
    0,
  )
}

function buildProjectPackageTimelineMarkdown(
  projectName: string,
  ownerName: string,
  timeline: ProjectPackageTimeline,
  relatedTodoDetailsByOperation: Map<number, OperationRelatedTodoExportDetail[]>,
) {
  const lines = [
    `# ${textValue(projectName, '未命名项目')} 项目时间线`,
    '',
    `- 项目负责人：${textValue(ownerName, '未填写')}`,
    `- 安装包操作记录：${countPackageItems(timeline)} 条`,
    `- 导出时间：${formatExportDateTime(new Date())}`,
  ]

  if (timeline.events.length === 0) {
    lines.push('', '暂无项目事件。')
    return `${lines.join('\n')}\n`
  }

  timeline.events.forEach((event, eventIndex) => {
    const createdAt = formatExportDateTime(event.createdAt)
    lines.push(
      '',
      `## ${createdAt}`,
      '',
      `### ${eventIndex + 1}. ${textValue(event.title, '未命名事件')}`,
      '',
      `- 交付人：${textValue(event.assigneeName, '未指派')}`,
      '',
      '### 操作文档',
      '',
    )
    if (event.operations.length === 0) {
      lines.push('暂无操作文档。', '')
    } else {
      event.operations.forEach((operation, index) => {
        lines.push(
          ...buildOperationMarkdown(
            operation,
            relatedTodoDetailsByOperation.get(operation.id) ?? [],
            `#### ${index + 1}.`,
          ),
          '',
        )
      })
    }

    if (event.groups.length === 0) {
      lines.push('暂无安装包。', '')
      return
    }

    event.groups
      .slice()
      .sort((left, right) => left.packageName.localeCompare(right.packageName, 'zh-CN'))
      .forEach((group) => {
      lines.push(
        ...buildPackageTimelineMarkdown(group, relatedTodoDetailsByOperation, '####'),
        '',
      )
    })
  })

  return `${lines.join('\n')}\n`
}

export async function getProjectPackageTimeline(projectId: number) {
  const [eventsResult, groupsResult, itemsResult, operationsResult, operationTodosResult] = await Promise.all([
    query<EventRow>(
      `
      select e.id,
             e.type,
             e.status,
             e.title,
             e.assignee_user_id,
             e.assigned_by_user_id,
             e.assigned_at,
             e.delivery_date,
             e.created_at,
             e.updated_at,
             assignee.email as assignee_email,
             assignee.display_name as assignee_display_name,
             assigner.email as assigner_email,
             assigner.display_name as assigner_display_name
      from project_package_events e
      left join users assignee on assignee.id = e.assignee_user_id
      left join users assigner on assigner.id = e.assigned_by_user_id
      where e.project_id = $1
      order by e.created_at asc, e.id asc
      `,
      [projectId],
    ),
    query<GroupRow>(
      `
      select g.id, g.project_package_event_id, g.package_name, g.created_at
      from project_package_groups g
      join project_package_events e on e.id = g.project_package_event_id
      where e.project_id = $1
      order by g.created_at asc, g.id asc
      `,
      [projectId],
    ),
    query<ItemRow>(
      `
      select i.id,
             i.project_package_group_id,
             i.source_package_id,
             i.source_package_name,
             i.channel,
             i.channel_label,
             i.arch,
             i.version,
             i.object_key,
             i.object_last_modified,
             i.size_bytes::text,
             i.created_at
      from project_package_items i
      join project_package_groups g on g.id = i.project_package_group_id
      join project_package_events e on e.id = g.project_package_event_id
      where e.project_id = $1
      order by i.created_at asc, i.id asc
      `,
      [projectId],
    ),
    query<OperationRow>(
      `
      select o.id,
             o.project_package_event_id,
             o.project_package_group_id,
             o.kind,
             o.status,
             o.title,
             o.label,
             o.content,
             o.completed,
             o.auto_generated,
             o.created_at,
             o.updated_at
      from project_package_operations o
      join project_package_events e on e.id = o.project_package_event_id
      where e.project_id = $1
      order by o.created_at asc, o.id asc
      `,
      [projectId],
    ),
    query<OperationTodoRow>(
      `
      select t.project_package_operation_id,
             t.todo_id,
             t.note
      from project_package_operation_todos t
      join project_package_operations o on o.id = t.project_package_operation_id
      join project_package_events e on e.id = o.project_package_event_id
      where e.project_id = $1
      order by t.created_at asc, t.todo_id asc
      `,
      [projectId],
    ),
  ])

  const groupsByEvent = new Map<number, ProjectPackageGroup[]>()
  const groupMap = new Map<number, ProjectPackageGroup>()
  for (const row of groupsResult.rows) {
    const group: ProjectPackageGroup = {
      id: Number(row.id),
      packageName: row.package_name,
      items: [],
      operations: [],
    }
    const eventId = Number(row.project_package_event_id)
    const groups = groupsByEvent.get(eventId) ?? []
    groups.push(group)
    groupsByEvent.set(eventId, groups)
    groupMap.set(group.id, group)
  }

  for (const row of itemsResult.rows) {
    const group = groupMap.get(Number(row.project_package_group_id))
    if (!group) continue
    group.items.push({
      id: Number(row.id),
      sourcePackageId: row.source_package_id,
      sourcePackageName: row.source_package_name,
      packageName: group.packageName,
      channel: row.channel,
      channelLabel: row.channel_label,
      arch: row.arch,
      version: row.version,
      objectKey: row.object_key,
      objectLastModified: row.object_last_modified
        ? formatDateTime(row.object_last_modified)
        : undefined,
      sizeBytes: row.size_bytes ? Number(row.size_bytes) : undefined,
      createdAt: formatDateTime(row.created_at),
    })
  }

  const relatedTodoIdsByOperation = new Map<number, number[]>()
  const relatedTodoNotesByOperation = new Map<number, Record<number, string>>()
  for (const row of operationTodosResult.rows) {
    const operationId = Number(row.project_package_operation_id)
    const todoIds = relatedTodoIdsByOperation.get(operationId) ?? []
    todoIds.push(Number(row.todo_id))
    relatedTodoIdsByOperation.set(operationId, todoIds)
    const todoNotes = relatedTodoNotesByOperation.get(operationId) ?? {}
    todoNotes[Number(row.todo_id)] = row.note ? decryptText(row.note) : ''
    relatedTodoNotesByOperation.set(operationId, todoNotes)
  }

  const eventOperationsByEvent = new Map<number, ProjectPackageOperation[]>()
  for (const row of operationsResult.rows) {
    const operation: ProjectPackageOperation = {
      id: Number(row.id),
      kind: row.kind,
      title: decryptText(row.title),
      label: row.label,
      content: row.content ? decryptText(row.content) : '',
      status: ensureProjectPackageOperationStatus(row.status),
      relatedTodoIds: relatedTodoIdsByOperation.get(Number(row.id)) ?? [],
      relatedTodoNotes: relatedTodoNotesByOperation.get(Number(row.id)) ?? {},
      completed: row.completed,
      autoGenerated: row.auto_generated,
      createdAt: formatDateTime(row.created_at),
      updatedAt: formatDateTime(row.updated_at),
    }
    if (row.project_package_group_id) {
      const group = groupMap.get(Number(row.project_package_group_id))
      group?.operations.push(operation)
    } else {
      const eventId = Number(row.project_package_event_id)
      const operations = eventOperationsByEvent.get(eventId) ?? []
      operations.push(operation)
      eventOperationsByEvent.set(eventId, operations)
    }
  }

  return {
    projectId,
    events: eventsResult.rows.map((row) => ({
      assignedAt: row.assigned_at ? formatDateTime(row.assigned_at) : undefined,
      assignedByName: row.assigned_by_user_id
        ? displayUserName({
            email: row.assigner_email,
            display_name: row.assigner_display_name,
          })
        : undefined,
      assignedByUserId: row.assigned_by_user_id ? Number(row.assigned_by_user_id) : undefined,
      assigneeName: row.assignee_user_id
        ? displayUserName({
            email: row.assignee_email,
            display_name: row.assignee_display_name,
          })
        : undefined,
      assigneeUserId: row.assignee_user_id ? Number(row.assignee_user_id) : undefined,
      id: Number(row.id),
      type: row.type,
      status: ensureProjectPackageEventStatus(row.status),
      title: decryptText(row.title),
      createdAt: formatDateTime(row.created_at),
      deliveryDate: row.delivery_date ? formatDate(row.delivery_date) : formatDate(row.created_at),
      updatedAt: formatDateTime(row.updated_at),
      operations: eventOperationsByEvent.get(Number(row.id)) ?? [],
      groups: groupsByEvent.get(Number(row.id)) ?? [],
    })),
  } satisfies ProjectPackageTimeline
}

